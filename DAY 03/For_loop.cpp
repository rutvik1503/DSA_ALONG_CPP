// Write a simple for loop program in c++

#include <iostream>
using namespace std;

int main()
{
    // Create a variable that value is 01
    int a;

    cout << endl;

    // Apply for loop to print 01 to 10 number
    for (a=1; a<=10; a++)
    {
        // Print the value of a
        cout << a << endl;
    }

    cout << endl;

    return 0;
    
}